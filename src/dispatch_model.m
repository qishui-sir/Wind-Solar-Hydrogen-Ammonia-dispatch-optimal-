    zeros(max_delay_days, 1));
if ~(isnumeric(initial_cohorts_kg) && ...
        numel(initial_cohorts_kg) == max_delay_days && ...
        all(isfinite(initial_cohorts_kg(:))) && ...
        all(initial_cohorts_kg(:) >= 0))
    error('dispatch_model:bad_contract_cohorts', ...
        'initial_cohorts_kg must contain one nonnegative value per delay day.');
end
contract.initial_cohorts_kg = initial_cohorts_kg(:);
end

function [delivery, contract] = strict_delivery_variable(contract)
delay_offsets = 0:contract.max_delay_days;
initial_due_day = 1 - (1:contract.max_delay_days)';
new_due_day = (1:contract.day_count)';
obligation_due_day = [initial_due_day; new_due_day];
obligation_kg = [contract.initial_cohorts_kg; ...
    contract.daily_quantity_kg * ones(contract.day_count, 1)];
delivery_day = obligation_due_day + delay_offsets;
valid_delivery = delivery_day >= 1 & ...
    delivery_day <= contract.day_count;
upper_bound = obligation_kg .* ones(1, numel(delay_offsets));
upper_bound(~valid_delivery) = 0;

delivery = optimvar('contract_delivery', ...
    numel(obligation_kg), numel(delay_offsets), ...
    'LowerBound', 0, 'UpperBound', upper_bound);
contract.obligation_due_day = obligation_due_day;
contract.obligation_kg = obligation_kg;
contract.delivery_day = delivery_day;
contract.must_clear_in_horizon = contract.terminal_clear | ...
    obligation_due_day + contract.max_delay_days <= contract.day_count;
end

function prob = add_strict_delivery_constraints( ...
        prob, delivery, daily_nh3_kg, contract)
obligation_count = numel(contract.obligation_kg);
clear_indices = find(contract.must_clear_in_horizon);
carry_indices = find(~contract.must_clear_in_horizon);
clearance = optimconstr(numel(clear_indices), 1);
for constraint_index = 1:numel(clear_indices)
    obligation_index = clear_indices(constraint_index);
    delivered_kg = sum(delivery(obligation_index, :));
    clearance(constraint_index) = delivered_kg == ...
        contract.obligation_kg(obligation_index);
end
prob.Constraints.contract_cohort_clearance = clearance;
if ~isempty(carry_indices)
    carryover = optimconstr(numel(carry_indices), 1);
    for constraint_index = 1:numel(carry_indices)
        obligation_index = carry_indices(constraint_index);
        carryover(constraint_index) = ...
            sum(delivery(obligation_index, :)) <= ...
            contract.obligation_kg(obligation_index);
    end
    prob.Constraints.contract_cohort_carryover = carryover;
end

daily_supply = optimconstr(contract.day_count, 1);
for day_index = 1:contract.day_count
    delivered_today = 0;
    for obligation_index = 1:obligation_count
        offset_index = find( ...
            contract.delivery_day(obligation_index, :) == day_index, ...
            1, 'first');
        if ~isempty(offset_index)
            delivered_today = delivered_today + ...
                delivery(obligation_index, offset_index);
        end
    end
    daily_supply(day_index) = delivered_today <= daily_nh3_kg(day_index);
end
prob.Constraints.contract_daily_supply = daily_supply;
end

function validate_initial_state(state, storage_limits, module_count, hb)
if ~(isnumeric(state.h2_kg) && isscalar(state.h2_kg) && ...
        isfinite(state.h2_kg) && ...
        state.h2_kg >= storage_limits.min_mass - 1e-6 && ...
        state.h2_kg <= storage_limits.max_mass + 1e-6)
    error('dispatch_model:bad_initial_h2', ...
        'initial_state.h2_kg is outside physical storage bounds.');
end
if ~(isnumeric(state.ael_online_modules) && ...
        isscalar(state.ael_online_modules) && ...
        state.ael_online_modules == floor(state.ael_online_modules) && ...
        state.ael_online_modules >= 0 && ...
        state.ael_online_modules <= module_count)
    error('dispatch_model:bad_initial_ael', ...
        'initial AEL online modules must be a valid integer count.');
end
if ~isempty(state.hb_load) && ...
        ~(isnumeric(state.hb_load) && isscalar(state.hb_load) && ...
        isfinite(state.hb_load) && state.hb_load >= hb.min_load && ...
        state.hb_load <= hb.max_load)
    error('dispatch_model:bad_initial_hb', ...
        'initial HB load must be within operating bounds.');
end
end

function validate_fixed_vector(value, expected_count, name)
if ~isnumeric(value) || numel(value) ~= expected_count || ...
        any(~isfinite(value(:)))
    error('dispatch_model:bad_fixed_plan', ...
        'fixed_plan.%s must contain %d finite values.', ...
        name, expected_count);
end
end

function samples_per_day = integer_samples_per_day(dt)
samples_per_day = round(24 / dt);
if abs(samples_per_day - 24 / dt) > 1e-9
    error('baseline:bad_contract_time_step', ...
        'Contract mode requires dt to divide 24 hours exactly.');
end
end

