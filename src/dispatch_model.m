contract.daily_quantity_kg = [];
contract.daily_quantity_upper_kg = [];
contract.lcoa_cap_usd_per_t = [];
contract.samples_per_day = [];
contract.day_count = [];
contract.strict_delivery = false;
contract.terminal_clear = true;
contract.initial_cohorts_kg = [];
if ~contract.enabled
    return
end

samples_per_day = integer_samples_per_day(dt);
if mod(T, samples_per_day) ~= 0
    error('baseline:contract_requires_complete_days', ...
        'Contract mode requires a whole number of days.');
end
max_delay_days = option_value(options, 'max_delay_days', 7);
if ~(isnumeric(max_delay_days) && isscalar(max_delay_days) && ...
        isfinite(max_delay_days) && max_delay_days >= 0 && ...
        max_delay_days == floor(max_delay_days))
    error('baseline:bad_contract_delay', ...
        'max_delay_days must be a nonnegative integer.');
end
daily_upper = option_value(options, 'daily_quantity_upper_kg', ...
    hb_max_load * nh3_rate * 24);
if ~(isnumeric(daily_upper) && isscalar(daily_upper) && ...
        isfinite(daily_upper) && daily_upper > 0)
    error('baseline:bad_contract_upper_bound', ...
        'daily_quantity_upper_kg must be positive.');
end
daily_quantity = option_value(options, 'fixed_daily_quantity_kg', []);
if ~(isnumeric(daily_quantity) && isscalar(daily_quantity) && ...
        isfinite(daily_quantity) && daily_quantity > 0 && ...
        daily_quantity <= daily_upper + 1e-9)
    error('baseline:bad_fixed_contract_quantity', ...
        ['fixed_daily_quantity_kg must be positive and no greater ', ...
        'than daily_quantity_upper_kg.']);
end
lcoa_cap = option_value(options, 'lcoa_cap_usd_per_t', []);
if ~isempty(lcoa_cap) && ~(isnumeric(lcoa_cap) && isscalar(lcoa_cap) && ...
        isfinite(lcoa_cap) && lcoa_cap > 0)
    error('baseline:bad_lcoa_cap', ...
        'lcoa_cap_usd_per_t must be empty or positive.');
end

contract.max_delay_days = max_delay_days;
contract.daily_quantity_kg = daily_quantity;
contract.daily_quantity_upper_kg = daily_upper;
contract.lcoa_cap_usd_per_t = lcoa_cap;
contract.samples_per_day = samples_per_day;
