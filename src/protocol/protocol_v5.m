function checksum = checksum_value(value)
if isstruct(value) && isfield(value, 'Seal')
    value = rmfield(value, 'Seal');
end

bytes = uint8(jsonencode(value));
hash_value = 2166136261;
for byte_index = 1:numel(bytes)
    hash_value = bitxor(uint32(hash_value), uint32(bytes(byte_index)));
    hash_value = mod(double(hash_value) * 16777619, 2^32);
end
checksum = string(sprintf('%08X', hash_value));
end
