function output = protocol_v5_dispatch(action, value)
if isstring(action) && isscalar(action)
    action = char(action);
end
if ~ischar(action)
    error('protocol_v5:bad_action', ...
        ['action must be verify, checksum, v5_1, verify_v5_1, ', ...
        'v5_2, or verify_v5_2.']);
end

switch lower(strtrim(action))
    case 'verify'
        output = verify_protocol(value);
    case 'checksum'
        output = checksum_value(value);
    case 'v5_1'
        output = create_protocol_v5_1();
    case 'verify_v5_1'
        output = verify_protocol_v5_1(value);
    case 'v5_2'
        output = create_protocol_v5_2();
    case 'verify_v5_2'
        output = verify_protocol_v5_2(value);
    otherwise
        error('protocol_v5:bad_action', ...
            ['action must be verify, checksum, v5_1, verify_v5_1, ', ...
            'v5_2, or verify_v5_2.']);
end
end

function is_valid = verify_protocol(protocol)
is_valid = isstruct(protocol) && isfield(protocol, 'Seal') && ...
    isfield(protocol, 'ProtocolVersion') && ...
    string(protocol.ProtocolVersion) == "5.0.0" && ...
    string(protocol.Seal) == checksum_value(protocol);
end

