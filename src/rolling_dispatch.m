function history = record_carbon_day(history, day_index, ...
        daily_emissions_kg, daily_nh3_kg, state, params, ...
        daily_contract_kg, contract_enabled, remaining_time_count)
debt_kg = state.co2_emitted_kg ...
    - params.environment.co2_limit * state.nh3_produced_kg;
history.daily_emissions_kg(day_index) = daily_emissions_kg;
history.daily_nh3_kg(day_index) = daily_nh3_kg;
history.cumulative_emissions_kg(day_index) = state.co2_emitted_kg;
history.cumulative_nh3_kg(day_index) = state.nh3_produced_kg;
history.cumulative_debt_kg(day_index) = debt_kg;
if contract_enabled
    remaining_reference_nh3_kg = remaining_contract_reference_nh3_kg( ...
        params, daily_contract_kg, remaining_time_count);
    history.remaining_reference_nh3_kg(day_index) = ...
        remaining_reference_nh3_kg;
    history.reachability_margin_kg(day_index) = ...
        params.environment.co2_limit * remaining_reference_nh3_kg ...
        - debt_kg;
else
    [~, available_budget_kg] = absolute_carbon_budget_schedule( ...
        params, daily_contract_kg, remaining_time_count, 0);
    history.remaining_reference_nh3_kg(day_index) = 0;
    history.reachability_margin_kg(day_index) = ...
        available_budget_kg - state.co2_emitted_kg;
end
history.completed_days = day_index;
end

function remaining_kg = remaining_contract_reference_nh3_kg( ...
        params, daily_contract_kg, remaining_time_count)
