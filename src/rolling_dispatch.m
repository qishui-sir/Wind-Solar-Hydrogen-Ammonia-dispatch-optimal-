function [result, run_info, metrics] = rolling_dispatch(config)
% ROLLING_DISPATCH Run forecast planning, realtime recourse, and state handoff.
% The function reads one input MAT file, plans 72 hours, commits 24 hours,
% replays those controls against observed renewable power, and repeats.

if nargin < 1 || isempty(config)
    config = struct();
end
project_dir = project_root();
add_project_paths(project_dir);

source_mat_path = option_value(config, 'source_mat_path', ...
    fullfile(project_dir, 'runs', 'stage1', ...
    'zhou_s2_baseline_2022_latest.mat'));
save_output = option_value(config, 'save_output', true);
verbose = option_value(config, 'verbose', true);
scheme = string(option_value(config, 'scheme', ...
    "contract_plan_and_hb_smoothing"));
forecast_mode = string(option_value(config, 'forecast_mode', ...
    "simulated_persistence"));
loaded = load_input(source_mat_path);
params = loaded.params;
renewable_data = loaded.renewable_data;
source_run_info = loaded.run_info;
subprotocol = protocol_v5('v5_1');
validate_configuration(config, renewable_data, subprotocol, ...
    scheme, forecast_mode);
h2_reserve = h2_reserve_settings(config, subprotocol);
joint = joint_coordination_settings(config, params, subprotocol);
params = apply_joint_coordination_params(params, joint);
restoration = rolling_restoration_settings(config);

hour_count = renewable_data.time_count;
samples_per_day = round(24 / params.time.step);
day_count = hour_count / samples_per_day;
data_year = source_year(source_run_info, renewable_data);
output_dir = option_value(config, 'output_dir', ...
    fullfile(project_dir, 'runs', 'rolling'));
output_path = rolling_output_path( ...
    output_dir, scheme, data_year, h2_reserve, joint);
contract_enabled = scheme == "contract_plan_and_hb_smoothing";

run_info = initial_run_info(source_mat_path, scheme, forecast_mode, ...
    subprotocol, data_year, day_count, output_path, save_output);
run_info.h2_reserve = h2_reserve.summary;
run_info.joint = joint.summary;
run_info.restoration = restoration.summary;
run_info.allow_infeasible_continuation = ...
    restoration.allow_infeasible_continuation;
result = [];
metrics = [];

forecast_source = prepare_forecast_source( ...
    renewable_data, config, forecast_mode, subprotocol, data_year);
run_info.forecast_fallback_source = forecast_source.fallback_source;
storage_limits = h2_storage_limits( ...
    params.h2_storage, params.unit.h2_density);
annual_initial_h2_kg = storage_limits.initial_mass;
if option_value(config, 'dry_run', false)
    first_forecast = forecast_window( ...
        forecast_source, renewable_data, 1, ...
        min(subprotocol.RollingDispatch.PlanningHours, hour_count));
    dry_state = initial_rolling_state( ...
        annual_initial_h2_kg, subprotocol);
    dry_remaining_after_commit_count = max( ...
        0, hour_count - round(24 / params.time.step));
    [dry_h2_reserve, dry_h2_reserve_gate] = ...
        gated_h2_reserve_for_day(h2_reserve, joint, dry_state, ...
        params, subprotocol.Contract.DailyQuantityKG, subprotocol, ...
        dry_remaining_after_commit_count);
    dry_options = planning_options(dry_state, subprotocol, ...
        subprotocol.Contract.DailyQuantityKG, contract_enabled, ...
        first_forecast.time_count == hour_count, ...
        annual_initial_h2_kg, params, ...
        hour_count - first_forecast.time_count, 0, ...
        first_forecast.time_count, first_forecast, ...
        dry_h2_reserve, joint.contract_pacing_aggressiveness);
    run_info.status = "ready";
    run_info.first_forecast_hour_count = first_forecast.time_count;
    run_info.first_h2_reserve = dry_options.h2_reserve;
    run_info.first_h2_reserve_gate = dry_h2_reserve_gate;
    run_info.first_production = dry_options.production;
    run_info.output_path = "";
    return
end

state = initial_rolling_state(annual_initial_h2_kg, subprotocol);
realized = empty_solution(hour_count, annual_initial_h2_kg);
day_ahead = empty_plan(hour_count);
records = empty_solver_records(day_count);
carbon_history = empty_carbon_history(day_count);
carbon_reserve_quantile = option_value( ...
    config, 'carbon_reserve_quantile', ...
    default_carbon_reserve_quantile());
carbon_reserve_history = empty_carbon_reserve_history( ...
    day_count, carbon_reserve_quantile, ...
    minimum_absolute_carbon_reserve_kg(params, contract_enabled));
production_pacing_history = empty_production_pacing_history(day_count);
hb_recourse_history = empty_hb_recourse_history(day_count);
daily_contract_kg = subprotocol.Contract.DailyQuantityKG;
if contract_enabled
    carbon_history.accounting = "annual_cumulative_reachability";
else
    carbon_history.accounting = "annual_cumulative_absolute_budget";
end
run_info.carbon_accounting = carbon_history.accounting;
failure_context = struct();

try
    for day_index = 1:day_count
        failure_context = struct('day_index', day_index, 'state', state);
        first_hour = (day_index - 1) * samples_per_day + 1;
        plan_hour_count = min( ...
            subprotocol.RollingDispatch.PlanningHours, ...
            hour_count - first_hour + 1);
        plan_indices = first_hour:first_hour + plan_hour_count - 1;
        commit_indices = first_hour:first_hour + samples_per_day - 1;
        commit_count = numel(commit_indices);
        is_final_window = plan_indices(end) == hour_count;
        remaining_after_commit_count = hour_count - commit_indices(end);

        forecast_data = forecast_window( ...
            forecast_source, renewable_data, day_index, plan_hour_count);
        [effective_h2_reserve, h2_reserve_gate] = ...
            gated_h2_reserve_for_day(h2_reserve, joint, state, ...
            params, daily_contract_kg, subprotocol, ...
            remaining_after_commit_count);
        [base_carbon_reserve_kg, carbon_reserve_history] = ...
            carbon_reserve_for_day( ...
            carbon_reserve_history, day_index, params);
        h2_carbon_guard_kg = h2_reserve_carbon_guard_kg( ...
            params, daily_contract_kg, effective_h2_reserve, subprotocol);
        carbon_reserve_kg = max(base_carbon_reserve_kg, ...
            h2_carbon_guard_kg);
        failure_context.carbon_reserve_kg = carbon_reserve_kg;
        failure_context.base_carbon_reserve_kg = base_carbon_reserve_kg;
        failure_context.h2_carbon_guard_kg = h2_carbon_guard_kg;
        plan_options = planning_options(state, subprotocol, ...
            daily_contract_kg, contract_enabled, is_final_window, ...
            annual_initial_h2_kg, params, ...
            hour_count - plan_indices(end), carbon_reserve_kg, ...
            plan_hour_count, forecast_data, effective_h2_reserve, ...
            joint.contract_pacing_aggressiveness);
        failure_context.plan_options = plan_options;
        if contract_enabled
            requested_production_target_kg = NaN;
        else
            requested_production_target_kg = ...
                plan_options.carbon.production_target_at_commit_kg;
        end
        applied_production_target_kg = requested_production_target_kg;
        production_pacing_history.requested_target_kg(day_index) = ...
            requested_production_target_kg;
        plan_model = dispatch_model(params, forecast_data, plan_options);
        [plan_sol, plan_fval, plan_exitflag, plan_output, ...
            plan_time, plan_succeeded] = solve_dispatch( ...
            plan_model.problem, config, "day_ahead", true);
        applied_plan_reserve_kg = carbon_reserve_kg;
        applied_h2_reserve_scale = effective_h2_reserve.target_scale;
        if ~plan_succeeded && effective_h2_reserve.active
            [plan_sol, plan_fval, plan_exitflag, plan_output, ...
                plan_time, plan_succeeded, plan_options, ...
                applied_h2_reserve_scale, carbon_reserve_kg, ...
                h2_carbon_guard_kg] = project_h2_reserve_plan( ...
                config, state, subprotocol, daily_contract_kg, ...
                contract_enabled, is_final_window, annual_initial_h2_kg, ...
                params, hour_count - plan_indices(end), ...
                base_carbon_reserve_kg, plan_hour_count, forecast_data, ...
                effective_h2_reserve, ...
                joint.contract_pacing_aggressiveness, plan_time);
            failure_context.plan_options = plan_options;
            failure_context.carbon_reserve_kg = carbon_reserve_kg;
            failure_context.h2_carbon_guard_kg = h2_carbon_guard_kg;
            applied_plan_reserve_kg = carbon_reserve_kg;
        end
        if ~plan_succeeded
            projection_options = plan_options;
            projection_options.carbon.commit_reserve_kg = 0;
            projection_options.objective_mode = ...
                "minimize_commit_carbon_debt";
            projection_model = dispatch_model( ...
                params, forecast_data, projection_options);
            [projection_sol, ~, projection_exitflag, projection_output, ...
                projection_time, projection_succeeded] = ...
                solve_dispatch(projection_model.problem, config, ...
                "day_ahead_carbon_projection", true);
            if ~projection_succeeded
                if restoration.allow_infeasible_continuation
                    projection_options = restoration_plan_options( ...
                        plan_options, restoration);
                    projection_options.carbon.commit_reserve_kg = 0;
                    projection_options.objective_mode = ...
                        "minimize_commit_carbon_debt";
                    projection_model = dispatch_model( ...
                        params, forecast_data, projection_options);
                    [projection_sol, ~, projection_exitflag, ...
                        projection_output, restore_projection_time] = ...
                        solve_dispatch(projection_model.problem, config, ...
                        "day_ahead_restoration_projection");
                    projection_time = projection_time ...
                        + restore_projection_time;
                    plan_options = projection_options;
                    plan_options.objective_mode = "economic";
                    carbon_reserve_kg = 0;
                    h2_carbon_guard_kg = 0;
                    applied_plan_reserve_kg = 0;
                    production_pacing_history.day_ahead_restored( ...
                        day_index) = true;
                elseif contract_enabled || is_final_window
                    error('rolling_dispatch:solve_failed', ...
                        ['day_ahead_carbon_projection solve failed or ', ...
                         'did not converge. Exitflag: %d. Message: %s'], ...
                        projection_exitflag, projection_output.message);
                end
                target_options = projection_options;
                target_options.carbon.production_target_at_commit_kg = ...
                    state.nh3_produced_kg;
                target_options.objective_mode = "maximize_commit_nh3";
                target_model = dispatch_model( ...
                    params, forecast_data, target_options);
                [target_sol, ~, ~, ~, target_time] = solve_dispatch( ...
                    target_model.problem, config, ...
                    "day_ahead_production_projection");
                maximum_target_kg = state.nh3_produced_kg ...
                    + sum(target_sol.HB_load(1:commit_count)) ...
                    * params.HB.nh3_output * params.time.step;
                applied_production_target_kg = min( ...
                    requested_production_target_kg, maximum_target_kg);
                plan_options.carbon.production_target_at_commit_kg = max( ...
                    state.nh3_produced_kg, ...
                    applied_production_target_kg - 1e-3);
                projection_options = plan_options;
                projection_options.carbon.commit_reserve_kg = 0;
                projection_options.objective_mode = ...
                    "minimize_commit_carbon_debt";
                projection_model = dispatch_model( ...
                    params, forecast_data, projection_options);
                [projection_sol, ~, ~, ~, projected_target_time] = ...
                    solve_dispatch(projection_model.problem, config, ...
                    "day_ahead_projected_production");
                projection_time = projection_time + target_time ...
                    + projected_target_time;
                production_pacing_history.day_ahead_projected( ...
                    day_index) = true;
            end
            projection_nh3_kg = sum( ...
                projection_sol.HB_load(1:commit_count)) ...
                * params.HB.nh3_output * params.time.step;
            projection_emissions_kg = params.environment.grid_co2 ...
                * sum(projection_sol.p_purchase(1:commit_count)) ...
                * params.time.step;
            if projection_options.carbon.accounting == ...
                    "annual_cumulative_absolute_budget"
                available_plan_reserve_kg = ...
                    available_absolute_carbon_budget( ...
                    projection_options.carbon, commit_count) ...
                    - state.co2_emitted_kg - projection_emissions_kg;
            else
                projection_debt_kg = state.co2_emitted_kg ...
                    + projection_emissions_kg ...
                    - params.environment.co2_limit ...
                    * (state.nh3_produced_kg + projection_nh3_kg);
                commit_remaining_reference_kg = ...
                    projection_options.carbon.remaining_reference_nh3_kg ...
                    + (plan_hour_count - commit_count) ...
                    * projection_options.carbon.reference_nh3_per_step_kg;
                available_plan_reserve_kg = ...
                    params.environment.co2_limit ...
                    * commit_remaining_reference_kg - projection_debt_kg;
            end
            applied_plan_reserve_kg = min(carbon_reserve_kg, ...
                max(available_plan_reserve_kg, 0));
            plan_options.carbon.commit_reserve_kg = ...
                max(applied_plan_reserve_kg - 1e-3, 0);
            plan_model = dispatch_model( ...
                params, forecast_data, plan_options);
            [plan_sol, plan_fval, plan_exitflag, plan_output, ...
                projected_plan_time] = solve_dispatch( ...
                plan_model.problem, config, "day_ahead_projected");
            plan_time = plan_time + projection_time ...
                + projected_plan_time;
        end
        production_pacing_history.contract_commit_min_nh3_kg( ...
            day_index) = plan_options.production.commit_min_nh3_kg;
        production_pacing_history.contract_allowable_backlog_kg( ...
            day_index) = ...
            plan_options.production.allowable_backlog_after_commit_kg;
        production_pacing_history.contract_h2_commit_min_kg( ...
            day_index) = scalar_or_nan( ...
            plan_options.terminal.h2_commit_min_kg);
        production_pacing_history.h2_reserve_target_min_kg( ...
            day_index) = plan_options.h2_reserve.target_min_kg;
        production_pacing_history.h2_reserve_raw_deficit_kg( ...
            day_index) = plan_options.h2_reserve.raw_deficit_quantile_kg;
        production_pacing_history.h2_reserve_deficit_kg( ...
            day_index) = plan_options.h2_reserve.deficit_quantile_kg;
        production_pacing_history.h2_reserve_applied_scale( ...
            day_index) = applied_h2_reserve_scale;
        production_pacing_history.h2_reserve_projected(day_index) = ...
            applied_h2_reserve_scale ...
            < effective_h2_reserve.target_scale - 1e-12;
        production_pacing_history.h2_reserve_carbon_guard_kg( ...
            day_index) = h2_carbon_guard_kg;
        production_pacing_history.h2_reserve_gate_open(day_index) = ...
            h2_reserve_gate.open;
        production_pacing_history.h2_reserve_gate_reason(day_index) = ...
            h2_reserve_gate.reason;
        carbon_reserve_history.applied_reserve_kgco2(day_index) = ...
            applied_plan_reserve_kg;
        production_pacing_history.day_ahead_target_kg(day_index) = ...
            applied_production_target_kg;
        records = record_solver(records, day_index, "plan", ...
            plan_fval, plan_exitflag, plan_output, plan_time);

        day_ahead = assign_plan(day_ahead, commit_indices, ...
            plan_sol, forecast_data, commit_count);
        actual_data = renewable_slice(renewable_data, commit_indices);
        recourse_options = recourse_options_for_day( ...
            state, plan_sol, commit_count, day_index == day_count, ...
            annual_initial_h2_kg, params, daily_contract_kg, ...
            contract_enabled, subprotocol, applied_plan_reserve_kg, ...
            hour_count - commit_indices(end), ...
            plan_options.hydrogen.min_storage_kg_by_step( ...
            1:commit_count), ...
            plan_options.hydrogen.reserve_floor_soft, ...
            plan_options.hydrogen.reserve_slack_penalty_usd_per_kg, ...
            joint.contract_pacing_aggressiveness, ...
            restoration_from_options(plan_options));
        if ~contract_enabled
            recourse_options.carbon.production_target_at_commit_kg = ...
                applied_production_target_kg;
        end
        failure_context.plan_solution = plan_sol;
        failure_context.actual_data = actual_data;
        failure_context.recourse_options = recourse_options;
        recourse_model = dispatch_model( ...
            params, actual_data, recourse_options);
        [actual_sol, actual_fval, actual_exitflag, ...
            actual_output, actual_time, recourse_succeeded] = ...
            solve_dispatch(recourse_model.problem, config, ...
            "realtime", true);
        fallback_invoked = ~recourse_succeeded;
        if fallback_invoked
            target_hb = recourse_options.fixed_plan.HB_load;
            target_ael = recourse_options.fixed_plan.AEL_commitment;
            fallback_options = recourse_options;
            fallback_options.fixed_plan = rmfield( ...
                fallback_options.fixed_plan, 'HB_load');
            fallback_options.fixed_plan = rmfield( ...
                fallback_options.fixed_plan, 'AEL_commitment');
            fallback_options.fixed_plan.HB_load_upper = target_hb;
            fallback_options.fixed_plan.AEL_commitment_upper = target_ael;
            fallback_options.carbon.commit_reserve_kg = 0;
            if ~contract_enabled && day_index < day_count
                target_options = fallback_options;
                target_options.carbon.production_target_at_commit_kg = ...
                    state.nh3_produced_kg;
                target_options.objective_mode = "maximize_commit_nh3";
                target_model = dispatch_model( ...
                    params, actual_data, target_options);
                [target_sol, ~, ~, ~, target_time] = solve_dispatch( ...
                    target_model.problem, config, ...
                    "realtime_production_projection");
                maximum_target_kg = state.nh3_produced_kg ...
                    + sum(target_sol.HB_load) * params.HB.nh3_output ...
                    * params.time.step;
                realtime_target_kg = min( ...
                    applied_production_target_kg, maximum_target_kg);
                fallback_options.carbon.production_target_at_commit_kg = ...
                    max(state.nh3_produced_kg, realtime_target_kg - 1e-3);
                production_pacing_history.realtime_target_kg(day_index) = ...
                    realtime_target_kg;
                production_pacing_history.realtime_projected(day_index) = ...
                    realtime_target_kg < applied_production_target_kg - 1e-3;
            else
                target_time = 0;
                production_pacing_history.realtime_target_kg(day_index) = ...
                    applied_production_target_kg;
            end
            fallback_options.objective_mode = "minimize_carbon_debt";
            phase1_model = dispatch_model( ...
                params, actual_data, fallback_options);
            [phase1_sol, ~, ~, ~, phase1_time] = solve_dispatch( ...
                phase1_model.problem, config, "realtime_carbon_phase1");
            phase1_nh3_kg = sum(phase1_sol.HB_load) ...
                * params.HB.nh3_output * params.time.step;
            phase1_emissions_kg = params.environment.grid_co2 ...
                * sum(phase1_sol.p_purchase) * params.time.step;
            phase1_debt_kg = ...
                fallback_options.carbon.initial_emissions_kg ...
                + phase1_emissions_kg - params.environment.co2_limit ...
                * (fallback_options.carbon.initial_nh3_kg ...
                + phase1_nh3_kg);
            if fallback_options.carbon.accounting == ...
                    "annual_cumulative_absolute_budget"
                available_margin_kg = ...
                    available_absolute_carbon_budget( ...
                    fallback_options.carbon, commit_count) ...
                    - fallback_options.carbon.initial_emissions_kg ...
                    - phase1_emissions_kg;
            else
                available_margin_kg = ...
                    params.environment.co2_limit ...
                    * fallback_options.carbon.remaining_reference_nh3_kg ...
                    - phase1_debt_kg;
            end
            projected_reserve_kg = min( ...
                recourse_options.carbon.commit_reserve_kg, ...
                max(available_margin_kg, 0));
            fallback_options.carbon.commit_reserve_kg = ...
                max(projected_reserve_kg - 1e-3, 0);
            fallback_options.objective_mode = "minimize_hb_shortfall";
            phase2_model = dispatch_model( ...
                params, actual_data, fallback_options);
            [phase2_sol, ~, ~, ~, phase2_time] = solve_dispatch( ...
                phase2_model.problem, config, "realtime_hb_phase2");
            minimum_shortfall = sum(target_hb - phase2_sol.HB_load) ...
                * params.time.step;
            fallback_options.fixed_plan.max_hb_shortfall_load_hours = ...
                minimum_shortfall + 1e-5;
            fallback_options.objective_mode = "economic";
            recourse_model = dispatch_model( ...
                params, actual_data, fallback_options);
            [actual_sol, actual_fval, actual_exitflag, ...
                actual_output, phase3_time] = solve_dispatch( ...
                recourse_model.problem, config, "realtime_economic_phase3");
            actual_time = actual_time + target_time + phase1_time ...
                + phase2_time + phase3_time;
        end
        if ~fallback_invoked
            production_pacing_history.realtime_target_kg(day_index) = ...
                applied_production_target_kg;
        end
        records = record_solver(records, day_index, "recourse", ...
            actual_fval, actual_exitflag, actual_output, actual_time);
        actual_sol.P_AEL_start = ...
            recourse_model.context.AEL_start_power_per_module ...
            * actual_sol.SU_AEL;
        realized = assign_solution( ...
            realized, commit_indices, actual_sol);
        carbon_reserve_history.realized_shortfall_kwh(day_index) = ...
            renewable_shortfall_kwh( ...
            forecast_data, actual_data, commit_count, params);
        planned_purchase_kwh = sum( ...
            plan_sol.p_purchase(1:commit_count)) * params.time.step;
        actual_purchase_kwh = sum(actual_sol.p_purchase) * params.time.step;
        carbon_reserve_history.planned_purchase_kwh(day_index) = ...
            planned_purchase_kwh;
        carbon_reserve_history.actual_purchase_kwh(day_index) = ...
            actual_purchase_kwh;
        carbon_reserve_history.purchase_exposure_kwh(day_index) = ...
            max(actual_purchase_kwh - planned_purchase_kwh, 0);
        target_nh3_kg = sum(plan_sol.HB_load(1:commit_count)) ...
            * params.HB.nh3_output * params.time.step;
        actual_nh3_kg = sum(actual_sol.HB_load) ...
            * params.HB.nh3_output * params.time.step;
        hb_recourse_history.fallback_invoked(day_index) = fallback_invoked;
        hb_recourse_history.target_nh3_kg(day_index) = target_nh3_kg;
        hb_recourse_history.actual_nh3_kg(day_index) = actual_nh3_kg;
        hb_recourse_history.shortfall_nh3_kg(day_index) = ...
            max(target_nh3_kg - actual_nh3_kg, 0);
        hb_recourse_history.requested_carbon_reserve_kg(day_index) = ...
            recourse_options.carbon.commit_reserve_kg;
        if recourse_options.carbon.accounting == ...
                "annual_cumulative_absolute_budget"
            hb_recourse_history.realized_carbon_margin_kg(day_index) = ...
                available_absolute_carbon_budget( ...
                recourse_options.carbon, commit_count) ...
                - state.co2_emitted_kg ...
                - params.environment.grid_co2 * actual_purchase_kwh;
        else
            actual_carbon_debt_kg = state.co2_emitted_kg ...
                + params.environment.grid_co2 * actual_purchase_kwh ...
                - params.environment.co2_limit ...
                * (state.nh3_produced_kg + actual_nh3_kg);
            hb_recourse_history.realized_carbon_margin_kg(day_index) = ...
                params.environment.co2_limit ...
                * recourse_options.carbon.remaining_reference_nh3_kg ...
                - actual_carbon_debt_kg;
        end
        hb_recourse_history.target_ael_module_hours(day_index) = ...
            sum(plan_sol.n_ael(1:commit_count)) * params.time.step;
        hb_recourse_history.actual_ael_module_hours(day_index) = ...
            sum(actual_sol.n_ael) * params.time.step;
        hb_recourse_history.ael_shortfall_module_hours(day_index) = ...
            max(hb_recourse_history.target_ael_module_hours(day_index) ...
            - hb_recourse_history.actual_ael_module_hours(day_index), 0);

        daily_nh3_kg = sum(actual_sol.HB_load) ...
            * params.HB.nh3_output * params.time.step;
        [next_cohorts, expired_kg] = update_contract_cohorts( ...
            state.contract_cohorts_kg, daily_contract_kg, daily_nh3_kg);
        production_pacing_history.expired_contract_kg(day_index) = ...
            expired_kg;
        if contract_enabled && expired_kg > 1e-3 && ...
                ~restoration.allow_infeasible_continuation
            error('rolling_dispatch:strict_delivery_breach', ...
                'Contract cohort expired on operating day %d by %.6f kg.', ...
                day_index, expired_kg);
        end
        state.h2_kg = actual_sol.storage_H2(end);
        state.ael_online_modules = round(actual_sol.n_ael(end));
        state.hb_load = min(params.HB.max_load, ...
            max(params.HB.min_load, actual_sol.HB_load(end)));
        daily_emissions_kg = params.environment.grid_co2 ...
            * sum(actual_sol.p_purchase) * params.time.step;
        state.co2_emitted_kg = clean_nonnegative_state_value( ...
            state.co2_emitted_kg + daily_emissions_kg, ...
            'co2_emitted_kg');
        state.nh3_produced_kg = clean_nonnegative_state_value( ...
            state.nh3_produced_kg + daily_nh3_kg, ...
            'nh3_produced_kg');
        state.sell_kwh = clean_nonnegative_state_value( ...
            state.sell_kwh + sum(actual_sol.p_sell) ...
            * params.time.step, 'sell_kwh');
        state.curtail_kwh = clean_nonnegative_state_value( ...
            state.curtail_kwh + sum(actual_sol.p_curt) ...
            * params.time.step, 'curtail_kwh');
        state.renewable_kwh = clean_nonnegative_state_value( ...
            state.renewable_kwh ...
            + sum(actual_data.pv_power_kw + actual_data.pw_power_kw) ...
            * params.renewable.input_scale * params.time.step, ...
            'renewable_kwh');
        state.contract_cohorts_kg = next_cohorts;
        carbon_history = record_carbon_day(carbon_history, day_index, ...
            daily_emissions_kg, daily_nh3_kg, state, params, ...
            daily_contract_kg, contract_enabled, ...
            hour_count - commit_indices(end));

        if verbose
            fprintf(['Completed day %d/%d: plan %.2fs, ', ...
                'recourse %.2fs.\n'], ...
                day_index, day_count, plan_time, actual_time);
        end
    end

    terminal_contract_backlog_kg = 0;
    if contract_enabled
        terminal_contract_backlog_kg = sum(state.contract_cohorts_kg);
    end
    run_info.terminal_contract_backlog_kg = terminal_contract_backlog_kg;
    if contract_enabled && terminal_contract_backlog_kg > 1e-3 && ...
            ~restoration.allow_infeasible_continuation
        error('rolling_dispatch:terminal_contract_breach', ...
            'Year-end unserved contract is %.6f kg.', ...
            terminal_contract_backlog_kg);
    end
    if ~restoration.allow_infeasible_continuation
        require_annual_carbon_feasibility(state, params);
        require_annual_grid_feasibility(state, params);
    end
catch exception
    run_info.status = "requires_slack_diagnosis";
    run_info.failed_day = first_unfinished_day(records);
    run_info.error_id = string(exception.identifier);
    run_info.error_message = string(exception.message);
    run_info.solver_records = records;
    run_info.carbon_state = carbon_state_summary(state, params);
    run_info.grid_state = grid_state_summary(state, params);
    run_info.carbon_history = carbon_history;
    run_info.carbon_reserve_history = carbon_reserve_history;
    run_info.production_pacing_history = production_pacing_history;
    run_info.hb_recourse_history = hb_recourse_history;
    run_info.restoration.used_day_count = ...
        nnz(production_pacing_history.day_ahead_restored);
    run_info.restoration.expired_contract_kg = ...
        sum(production_pacing_history.expired_contract_kg, 'omitnan');
    run_info.slack_diagnosis = slack_diagnosis_plan();
    diagnosis = classify_failure(run_info, failure_context, params);
    run_info.infeasibility_diagnosis = diagnosis;
    if save_output
        ensure_directory(output_dir);
        save(output_path, 'run_info', 'params', 'renewable_data', ...
            'source_run_info', 'failure_context', 'diagnosis');
    end
    rethrow(exception)
end

context = result_context(params, renewable_data);
aggregate_output = aggregate_solver_output(records);
if verbose
    result = results(params, renewable_data, realized, 0, 1, ...
        aggregate_output, context);
else
    evalc('result = results(params, renewable_data, realized, 0, 1, aggregate_output, context);');
end
result.fval = -result.summary.net_profit;
result.cost.objective_value = result.fval;
result.optimization.mode = 'rolling_day_ahead_with_realtime_recourse';
result.optimization.objective_value = result.fval;
result.day_ahead = day_ahead;
result.carbon = carbon_history;
result.hb_recourse = hb_recourse_history;
metrics = calculate_metrics(result, params, renewable_data, day_ahead, ...
    subprotocol, daily_contract_kg, contract_enabled);
result.contract = metrics.Contract;

run_info.status = "completed";
run_info.solver_records = records;
final_carbon = carbon_state_summary(state, params);
run_info.carbon_accounting = carbon_history.accounting;
run_info.final_carbon_emissions_kg = final_carbon.emissions_kg;
run_info.final_nh3_kg = final_carbon.nh3_kg;
run_info.final_carbon_debt_kg = final_carbon.debt_kg;
final_grid = grid_state_summary(state, params);
run_info.grid_accounting = "annual_cumulative_observed_budget";
run_info.final_sell_kwh = final_grid.sell_kwh;
run_info.final_curtail_kwh = final_grid.curtail_kwh;
run_info.final_renewable_kwh = final_grid.renewable_kwh;
run_info.carbon_reserve_history = carbon_reserve_history;
run_info.production_pacing_history = production_pacing_history;
run_info.hb_recourse_history = hb_recourse_history;
run_info.restoration.used_day_count = ...
    nnz(production_pacing_history.day_ahead_restored);
run_info.restoration.expired_contract_kg = ...
    sum(production_pacing_history.expired_contract_kg, 'omitnan');
run_info.output_path = "";
if save_output
    ensure_directory(output_dir);
    run_info.output_path = string(output_path);
    save(output_path, 'result', 'run_info', 'metrics', 'params', ...
        'renewable_data', 'source_run_info');
end
end

