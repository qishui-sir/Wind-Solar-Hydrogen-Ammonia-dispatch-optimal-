function [effective_reserve, gate] = gated_h2_reserve_for_day( ...
        h2_reserve, joint, state, params, daily_contract_kg, ...
        subprotocol, remaining_after_commit_count)
effective_reserve = h2_reserve;
remaining_days_after_commit = ...
    remaining_after_commit_count * params.time.step / 24;
max_backlog_kg = subprotocol.Contract.MaxDelayDays * daily_contract_kg;
backlog_kg = sum(state.contract_cohorts_kg);
if max_backlog_kg > 0
    backlog_fraction = backlog_kg / max_backlog_kg;
else
    backlog_fraction = 0;
end
carbon_debt_kg = state.co2_emitted_kg ...
    - params.environment.co2_limit * state.nh3_produced_kg;
remaining_reference_kg = remaining_contract_reference_nh3_kg( ...
    params, daily_contract_kg, remaining_after_commit_count);
carbon_margin_kg = params.environment.co2_limit ...
    * remaining_reference_kg - carbon_debt_kg;
carbon_guard_kg = h2_gate_carbon_guard_kg( ...
    params, daily_contract_kg, joint);
gate = struct( ...
    'mode', joint.h2_reserve_gate_mode, ...
    'open', true, ...
    'reason', "open", ...
    'backlog_kg', backlog_kg, ...
    'backlog_fraction', backlog_fraction, ...
    'carbon_margin_kg', carbon_margin_kg, ...
    'carbon_guard_kg', carbon_guard_kg, ...
    'remaining_days_after_commit', remaining_days_after_commit);
if ~h2_reserve.active
    gate.open = false;
    gate.reason = "inactive_reserve";
    return
end
if joint.h2_reserve_gate_mode == "off"
    gate.reason = "gate_off";
    return
end
recovery_window_days = subprotocol.RollingDispatch.PlanningHours / 24 ...
    + subprotocol.Contract.MaxDelayDays;
if remaining_days_after_commit <= recovery_window_days
    gate.open = false;
    gate.reason = "year_end_h2_recovery_priority";
elseif backlog_fraction >= joint.h2_reserve_gate_backlog_fraction
    gate.open = false;
    gate.reason = "contract_backlog_priority";
elseif carbon_margin_kg < carbon_guard_kg
    gate.open = false;
    gate.reason = "carbon_reachability_priority";
end
if ~gate.open
    effective_reserve.target_scale = 0;
    effective_reserve.summary.target_scale = 0;
end
end

function guard_kg = h2_gate_carbon_guard_kg( ...
        params, daily_contract_kg, joint)
if joint.h2_reserve_gate_carbon_guard_days == 0
    guard_kg = 0;
    return
end
daily_h2_kg = daily_contract_kg * params.HB.lit_h2;
daily_ael_kwh = daily_h2_kg * params.AEL.common.spec_energy ...
    / params.unit.h2_density;
daily_hb_kwh = params.HB.nom_power * 1000 * 24;
daily_grid_emissions_kg = (daily_ael_kwh + daily_hb_kwh) ...
    * params.environment.grid_co2;
guard_kg = daily_grid_emissions_kg ...
    * joint.h2_reserve_gate_carbon_guard_days;
end

