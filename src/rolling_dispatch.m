function floor_kg = reserve_floor_trajectory( ...
        initial_kg, target_kg, step_count, storage_limits)
if target_kg > initial_kg
    floor_kg = initial_kg + (target_kg - initial_kg) ...
        * (1:step_count)' / step_count;
else
    floor_kg = target_kg * ones(step_count, 1);
end
floor_kg = min(storage_limits.max_mass, ...
    max(storage_limits.min_mass, floor_kg));
end

function deficit_quantile_kg = forecast_h2_deficit_quantile_kg( ...
        forecast_data, params, daily_contract_kg, ...
        lookahead_steps, quantile)
if lookahead_steps <= 0
    deficit_quantile_kg = 0;
    return
end
dt = params.time.step;
contract_hb_load = daily_contract_kg ...
    / (24 * params.HB.nh3_output);
contract_hb_load = min(params.HB.max_load, ...
    max(params.HB.min_load, contract_hb_load));
contract_h2_use_kg = contract_hb_load ...
    * params.HB.nh3_output * params.HB.lit_h2 * dt;
contract_hb_power_kw = contract_hb_load ...
    * params.HB.nom_power * 1000;
renewable_kw = (forecast_data.pv_power_kw(1:lookahead_steps) ...
    + forecast_data.pw_power_kw(1:lookahead_steps)) ...
    * params.renewable.input_scale;
available_ael_kw = min(params.AEL.common.max_power, ...
    max(renewable_kw - contract_hb_power_kw, 0));
h2_from_forecast_kg = available_ael_kw * dt ...
    / params.AEL.common.spec_energy * params.unit.h2_density;
cumulative_deficit_kg = cumsum( ...
    contract_h2_use_kg - h2_from_forecast_kg);
cumulative_deficit_kg = max(cumulative_deficit_kg, 0);
deficit_quantile_kg = prctile( ...
    cumulative_deficit_kg, 100 * quantile);
end

function surplus_h2_kg = forecast_renewable_surplus_h2_kg( ...
        forecast_data, params, daily_contract_kg, commit_steps)
if commit_steps <= 0
    surplus_h2_kg = 0;
    return
end
steps = min(commit_steps, forecast_data.time_count);
dt = params.time.step;
contract_hb_load = daily_contract_kg ...
    / (24 * params.HB.nh3_output);
contract_hb_load = min(params.HB.max_load, ...
    max(params.HB.min_load, contract_hb_load));
contract_hb_power_kw = contract_hb_load ...
    * params.HB.nom_power * 1000;
renewable_kw = (forecast_data.pv_power_kw(1:steps) ...
    + forecast_data.pw_power_kw(1:steps)) ...
    * params.renewable.input_scale;
available_ael_kw = min(params.AEL.common.max_power, ...
    max(renewable_kw - contract_hb_power_kw, 0));
surplus_h2_kg = sum(available_ael_kw) * dt ...
    / params.AEL.common.spec_energy * params.unit.h2_density;
end

function [sol, fval, exitflag, output, elapsed, succeeded] = ...
        solve_dispatch(problem, config, label, allow_failure)
if nargin < 4
    allow_failure = false;
end
solver_options = optimoptions('intlinprog', ...
    'Display', option_value(config, 'solver_display', 'none'), ...
    'ConstraintTolerance', 1e-5, ...
    'RelativeGapTolerance', option_value( ...
        config, 'relative_gap_tolerance', 1e-3));
max_time = option_value(config, 'max_time_seconds_per_solve', 180);
solver_options.MaxTime = max_time;
timer = tic;
[sol, fval, exitflag, output] = solve(problem, ...
    'Solver', 'intlinprog', 'Options', solver_options);
elapsed = toc(timer);
has_solution = isstruct(sol) && isfield(sol, 'P_AEL') && ...
    ~isempty(sol.P_AEL);
succeeded = has_solution && exitflag == 1 && ...
    output.constrviolation <= solver_options.ConstraintTolerance;
if ~succeeded && ~allow_failure
    error('rolling_dispatch:solve_failed', ...
        ['%s solve failed or did not converge. Exitflag: %d. ', ...
        'Message: %s'], label, exitflag, output.message);
end
end

function [sol, fval, exitflag, output, elapsed, succeeded, ...
        projected_options, applied_scale, projected_carbon_reserve_kg, ...
        projected_h2_carbon_guard_kg] = project_h2_reserve_plan( ...
        config, state, subprotocol, daily_contract_kg, ...
        contract_enabled, final_window, annual_initial_h2, params, ...
        remaining_time_count, base_carbon_reserve_kg, horizon_time_count, ...
        forecast_data, h2_reserve, contract_pacing_aggressiveness, ...
        elapsed)
projection_scales = [0.75, 0.50, 0.25, 0];
sol = struct();
fval = NaN;
exitflag = NaN;
output = struct('message', 'H2 reserve projection was not attempted.');
succeeded = false;
projected_h2_carbon_guard_kg = h2_reserve_carbon_guard_kg( ...
    params, daily_contract_kg, h2_reserve, subprotocol);
projected_carbon_reserve_kg = max( ...
    base_carbon_reserve_kg, projected_h2_carbon_guard_kg);
projected_options = planning_options(state, subprotocol, ...
    daily_contract_kg, contract_enabled, final_window, ...
    annual_initial_h2, params, remaining_time_count, ...
    projected_carbon_reserve_kg, horizon_time_count, ...
    forecast_data, h2_reserve, contract_pacing_aggressiveness);
applied_scale = h2_reserve.target_scale;
for scale_index = 1:numel(projection_scales)
    trial_reserve = h2_reserve;
    trial_reserve.target_scale = ...
        min(h2_reserve.target_scale, projection_scales(scale_index));
    trial_h2_carbon_guard_kg = h2_reserve_carbon_guard_kg( ...
        params, daily_contract_kg, trial_reserve, subprotocol);
    trial_carbon_reserve_kg = max( ...
        base_carbon_reserve_kg, trial_h2_carbon_guard_kg);
    trial_options = planning_options(state, subprotocol, ...
        daily_contract_kg, contract_enabled, final_window, ...
        annual_initial_h2, params, remaining_time_count, ...
        trial_carbon_reserve_kg, horizon_time_count, forecast_data, ...
        trial_reserve, contract_pacing_aggressiveness);
    trial_model = dispatch_model(params, forecast_data, trial_options);
    [trial_sol, trial_fval, trial_exitflag, trial_output, ...
        trial_elapsed, trial_succeeded] = solve_dispatch( ...
        trial_model.problem, config, ...
        sprintf('day_ahead_h2_projection_%.2f', ...
        trial_reserve.target_scale), true);
    elapsed = elapsed + trial_elapsed;
    sol = trial_sol;
    fval = trial_fval;
    exitflag = trial_exitflag;
    output = trial_output;
    projected_options = trial_options;
    applied_scale = trial_reserve.target_scale;
    projected_carbon_reserve_kg = trial_carbon_reserve_kg;
    projected_h2_carbon_guard_kg = trial_h2_carbon_guard_kg;
    if trial_succeeded
