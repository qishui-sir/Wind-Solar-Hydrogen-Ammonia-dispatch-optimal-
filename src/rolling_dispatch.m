function h2_min_kg = contract_h2_commit_min_kg( ...
        contract_enabled, params, annual_initial_h2, subprotocol, ...
        remaining_after_commit_count)
if ~contract_enabled
    h2_min_kg = [];
    return
end
h2_handoff_kg = h2_handoff_inventory_kg(params);
planning_days = subprotocol.RollingDispatch.PlanningHours / 24;
recovery_days = subprotocol.Contract.MaxDelayDays;
remaining_days = remaining_after_commit_count * params.time.step / 24;
if remaining_days <= planning_days
    h2_min_kg = annual_initial_h2;
else
    recovery_fraction = max(0, ...
        1 - (remaining_days - planning_days) / recovery_days);
    h2_min_kg = h2_handoff_kg + recovery_fraction ...
        * (annual_initial_h2 - h2_handoff_kg);
end
h2_min_kg = min(annual_initial_h2, max(h2_handoff_kg, h2_min_kg));
end

