function [reserve_kg, history] = carbon_reserve_for_day( ...
        history, day_index, params)
if day_index <= 2 || history.quantile == 0
    samples_kwh = zeros(0, 1);
else
    samples_kwh = history.purchase_exposure_kwh(2:day_index - 1);
end
sample_count = numel(samples_kwh);
if sample_count == 0
    reserve_kwh = 0;
else
    sorted_samples = sort(samples_kwh);
    rank_index = min(sample_count, ...
        ceil((sample_count + 1) * history.quantile));
    reserve_kwh = sorted_samples(rank_index);
end
reserve_kg = reserve_kwh * params.environment.grid_co2;
if day_index < numel(history.reserve_kgco2)
    reserve_kg = max(reserve_kg, history.minimum_reserve_kgco2);
else
    reserve_kg = 0;
end
reserve_kwh = reserve_kg / params.environment.grid_co2;
history.sample_count(day_index) = sample_count;
history.reserve_kwh(day_index) = reserve_kwh;
history.reserve_kgco2(day_index) = reserve_kg;
end

