function contract = contract_metrics( ...
        daily_nh3_kg, daily_contract_kg, max_delay_days)
day_count = numel(daily_nh3_kg);
backlog = zeros(day_count, 1);
for day_index = 1:day_count
    previous = 0;
    if day_index > 1
        previous = backlog(day_index - 1);
    end
    backlog(day_index) = max(0, ...
        previous + daily_contract_kg - daily_nh3_kg(day_index));
end

remaining = zeros(day_count, 1);
completion = NaN(day_count, 1);
tol = 1e-3;
for delivery_day = 1:day_count
    remaining(delivery_day) = daily_contract_kg;
    available = daily_nh3_kg(delivery_day);
    for contract_day = 1:delivery_day
        delivered = min(remaining(contract_day), available);
        remaining(contract_day) = remaining(contract_day) - delivered;
        available = available - delivered;
        if remaining(contract_day) <= tol && isnan(completion(contract_day))
            remaining(contract_day) = 0;
            completion(contract_day) = delivery_day;
        end
        if available <= tol
            break
        end
    end
end
delays = completion - (1:day_count)';
completed = delays(~isnan(delays));
if isempty(completed)
    maximum_delay = NaN;
else
    maximum_delay = max(completed);
end
contract = struct( ...
    'daily_quantity_kg', daily_contract_kg, ...
    'annual_quantity_t', daily_contract_kg * day_count / 1000, ...
    'daily_nh3_kg', daily_nh3_kg, ...
    'backlog_kg', backlog, ...
    'maximum_backlog_kg', max(backlog), ...
    'terminal_backlog_kg', backlog(end), ...
    'delivery_delay_days', delays, ...
    'maximum_delivery_delay_days', maximum_delay, ...
    'late_cohort_count', nnz(delays > max_delay_days), ...
    'unserved_cohort_count', nnz(remaining > tol));
end

