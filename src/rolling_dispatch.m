function source = prepare_forecast_source( ...
        renewable_data, config, forecast_mode, subprotocol, data_year)
source = struct('mode', forecast_mode);
if forecast_mode == "observed_oracle"
    if ~ismember(data_year, subprotocol.DataSplit.DevelopmentYears)
        error('rolling_dispatch:oracle_holdout_forbidden', ...
            'observed_oracle is restricted to frozen development years.');
    end
    source.fallback_source = ...
        "observed_development_oracle_not_forecast_claim";
    return
end
if forecast_mode == "simulated_persistence"
    if isfield(config, 'forecast_fallback')
        fallback = validate_development_fallback( ...
            config.forecast_fallback, subprotocol);
        source.pv_fallback = fallback.pv_power_kw(:);
        source.pw_fallback = fallback.pw_power_kw(:);
        source.fallback_source = ...
            "external_development_years_2022_2023";
        return
    end
    if ~ismember(data_year, subprotocol.DataSplit.DevelopmentYears)
        error('rolling_dispatch:missing_development_fallback', ...
            ['Target-year simulated forecasts require forecast_fallback ', ...
             'derived only from the frozen 2022/2023 development years.']);
    end
    samples_per_day = 24 / renewable_data_time_step(renewable_data);
    day_count = renewable_data.time_count / samples_per_day;
    source.pv_fallback = median(reshape( ...
        renewable_data.pv_power_kw, samples_per_day, day_count), 2);
    source.pw_fallback = median(reshape( ...
        renewable_data.pw_power_kw, samples_per_day, day_count), 2);
    source.fallback_source = "current_development_year_hour_median";
    return
end

forecast_table = option_value(config, 'forecast_table', table());
if ~istable(forecast_table)
    error('rolling_dispatch:bad_forecast_table', ...
        'forecast_table must be a MATLAB table.');
end
required = cellstr(subprotocol.Forecast.RealForecastInterface.RequiredFields);
missing = setdiff(required, forecast_table.Properties.VariableNames);
if ~isempty(missing)
    error('rolling_dispatch:bad_forecast_table', ...
        'forecast_table is missing: %s.', strjoin(missing, ', '));
end
source.table = forecast_table;
source.fallback_source = "not_applicable";
end

function fallback = validate_development_fallback(fallback, subprotocol)
required = {'source_years', 'pv_power_kw', 'pw_power_kw'};
for field_index = 1:numel(required)
    field_name = required{field_index};
    if ~isfield(fallback, field_name)
        error('rolling_dispatch:bad_forecast_fallback', ...
            'forecast_fallback must contain %s.', field_name);
    end
end
source_years = sort(double(fallback.source_years(:)));
development_years = sort(double( ...
    subprotocol.DataSplit.DevelopmentYears(:)));
if ~isequal(source_years, development_years)
    error('rolling_dispatch:bad_forecast_fallback', ...
        'forecast_fallback.source_years must be exactly 2022 and 2023.');
end
validate_fallback_profile(fallback.pv_power_kw, 'pv_power_kw');
validate_fallback_profile(fallback.pw_power_kw, 'pw_power_kw');
end

function validate_fallback_profile(profile, field_name)
if ~isnumeric(profile) || numel(profile) ~= 24 || ...
        any(~isfinite(profile(:))) || any(profile(:) < 0)
    error('rolling_dispatch:bad_forecast_fallback', ...
        'forecast_fallback.%s must contain 24 finite nonnegative values.', ...
        field_name);
end
end

function forecast = forecast_window( ...
        source, observed, day_index, hour_count)
if source.mode == "observed_oracle"
    first_hour = (day_index - 1) * 24 + 1;
    indices = first_hour:first_hour + hour_count - 1;
    forecast = struct( ...
        'time_count', hour_count, ...
        'pv_power_kw', observed.pv_power_kw(indices), ...
        'pw_power_kw', observed.pw_power_kw(indices));
    return
end
if source.mode == "simulated_persistence"
    if day_index == 1
        pv_profile = source.pv_fallback;
        pw_profile = source.pw_fallback;
    else
        previous = (day_index - 2) * 24 + (1:24);
        pv_profile = observed.pv_power_kw(previous);
        pw_profile = observed.pw_power_kw(previous);
    end
    repeat_count = ceil(hour_count / 24);
    forecast = struct();
