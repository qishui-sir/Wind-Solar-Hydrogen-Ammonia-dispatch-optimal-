quantile = 0;
end

function reserve = h2_reserve_settings(config, subprotocol)
quantile = option_value(config, 'h2_reserve_quantile', 0);
lookahead_days = option_value(config, 'h2_reserve_lookahead_days', 0);
if ~(isnumeric(quantile) && isscalar(quantile) && ...
        isfinite(quantile) && quantile >= 0 && quantile <= 1)
    error('rolling_dispatch:bad_h2_reserve_quantile', ...
        'h2_reserve_quantile must be a finite scalar in [0, 1].');
end
if quantile > 0 && lookahead_days == 0
    lookahead_days = subprotocol.Calibration.CandidateGrid ...
        .ReserveLookaheadDays(1);
end
if ~(isnumeric(lookahead_days) && isscalar(lookahead_days) && ...
        isfinite(lookahead_days) && lookahead_days >= 0 && ...
        lookahead_days == floor(lookahead_days))
    error('rolling_dispatch:bad_h2_reserve_lookahead', ...
        'h2_reserve_lookahead_days must be a nonnegative integer.');
end
maximum_lookahead_days = ...
    subprotocol.RollingDispatch.PlanningHours / 24;
if lookahead_days > maximum_lookahead_days
    error('rolling_dispatch:bad_h2_reserve_lookahead', ...
        ['h2_reserve_lookahead_days cannot exceed the frozen ', ...
         'planning horizon.']);
end
reserve = struct();
reserve.active = quantile > 0;
reserve.quantile = quantile;
reserve.lookahead_days = lookahead_days;
reserve.target_scale = option_value(config, 'h2_reserve_target_scale', 1);
if ~(isnumeric(reserve.target_scale) && isscalar(reserve.target_scale) && ...
        isfinite(reserve.target_scale) && reserve.target_scale >= 0 && ...
        reserve.target_scale <= 1)
    error('rolling_dispatch:bad_h2_reserve_target_scale', ...
        'h2_reserve_target_scale must be a finite scalar in [0, 1].');
end
reserve.method = "future_cumulative_h2_deficit_quantile";
reserve.soft = option_value(config, 'h2_reserve_soft', false);
if ~(islogical(reserve.soft) && isscalar(reserve.soft))
    error('rolling_dispatch:bad_h2_reserve_soft', ...
        'h2_reserve_soft must be a scalar logical.');
end
reserve.soft_penalty_usd_per_kg = option_value(config, ...
    'h2_reserve_soft_penalty_usd_per_kg', 100);
if ~(isnumeric(reserve.soft_penalty_usd_per_kg) && ...
        isscalar(reserve.soft_penalty_usd_per_kg) && ...
        isfinite(reserve.soft_penalty_usd_per_kg) && ...
        reserve.soft_penalty_usd_per_kg >= 0)
    error('rolling_dispatch:bad_h2_reserve_soft', ...
        ['h2_reserve_soft_penalty_usd_per_kg must be a finite ', ...
         'nonnegative scalar.']);
end
reserve.summary = struct( ...
    'active', reserve.active, ...
    'quantile', reserve.quantile, ...
    'lookahead_days', reserve.lookahead_days, ...
    'target_scale', reserve.target_scale, ...
    'soft', reserve.soft, ...
    'soft_penalty_usd_per_kg', reserve.soft_penalty_usd_per_kg, ...
    'method', reserve.method);
end

