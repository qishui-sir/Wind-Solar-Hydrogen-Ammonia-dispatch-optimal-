function [annual_budget_kg, available_at_start_kg, ...
        accrual_per_step_kg] = absolute_carbon_budget_schedule( ...
        params, daily_contract_kg, remaining_time_count, horizon_time_count)
annual_budget_kg = params.environment.co2_limit * daily_contract_kg * 365;
total_hours = params.time.hour_year * params.time.step;
elapsed_hours = (params.time.hour_year - remaining_time_count ...
    - horizon_time_count) * params.time.step;
borrowing_hours = 14 * 24;
available_at_start_kg = min(annual_budget_kg, ...
    annual_budget_kg * (elapsed_hours + borrowing_hours) / total_hours);
accrual_per_step_kg = annual_budget_kg * params.time.step / total_hours;
end

function available_budget_kg = available_absolute_carbon_budget( ...
        carbon, step_count)
available_budget_kg = min(carbon.annual_emissions_budget_kg, ...
    carbon.budget_available_at_start_kg ...
    + step_count * carbon.budget_accrual_per_step_kg);
end

