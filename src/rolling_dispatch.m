function [hydrogen, reserve] = hydrogen_reserve_options( ...
        state, forecast_data, params, daily_contract_kg, ...
        contract_enabled, h2_reserve, commit_steps, h2_commit_min_kg)
storage_limits = h2_storage_limits( ...
    params.h2_storage, params.unit.h2_density);
time_count = forecast_data.time_count;
base_floor_kg = storage_limits.min_mass * ones(time_count, 1);
base_target_kg = scalar_or_value( ...
    h2_commit_min_kg, h2_handoff_inventory_kg(params));
raw_deficit_quantile_kg = 0;
deficit_quantile_kg = 0;
reserve_target_kg = storage_limits.min_mass;
lookahead_steps = 0;
surplus_charge_cap_kg = 0;
active_commit_steps = min(commit_steps, time_count);
if contract_enabled && h2_reserve.active
    lookahead_steps = min(time_count, ...
        h2_reserve.lookahead_days * round(24 / params.time.step));
    raw_deficit_quantile_kg = forecast_h2_deficit_quantile_kg( ...
        forecast_data, params, daily_contract_kg, ...
        lookahead_steps, h2_reserve.quantile);
    deficit_quantile_kg = h2_reserve.target_scale ...
        * raw_deficit_quantile_kg;
    reserve_target_kg = storage_limits.min_mass ...
        + min(storage_limits.work_mass, deficit_quantile_kg);
    surplus_charge_cap_kg = forecast_renewable_surplus_h2_kg( ...
        forecast_data, params, daily_contract_kg, commit_steps);
    commit_contract_h2_use_kg = daily_contract_kg ...
        * params.HB.lit_h2 * active_commit_steps ...
        * params.time.step / 24;
    reserve_target_kg = min(reserve_target_kg, ...
        state.h2_kg - commit_contract_h2_use_kg ...
        + surplus_charge_cap_kg);
    reserve_target_kg = max(storage_limits.min_mass, ...
        reserve_target_kg);
end
target_kg = min(storage_limits.max_mass, ...
    max(base_target_kg, reserve_target_kg));
if active_commit_steps > 0
    base_floor_kg(1:active_commit_steps) = reserve_floor_trajectory( ...
        state.h2_kg, target_kg, active_commit_steps, ...
        storage_limits);
end
hydrogen = struct( ...
    'min_storage_kg_by_step', base_floor_kg, ...
    'reserve_floor_soft', h2_reserve.soft, ...
    'reserve_slack_penalty_usd_per_kg', ...
        h2_reserve.soft_penalty_usd_per_kg);
reserve = struct( ...
    'active', h2_reserve.active, ...
    'method', h2_reserve.method, ...
    'quantile', h2_reserve.quantile, ...
    'lookahead_days', h2_reserve.lookahead_days, ...
    'applied_scale', h2_reserve.target_scale, ...
    'soft', h2_reserve.soft, ...
    'soft_penalty_usd_per_kg', ...
        h2_reserve.soft_penalty_usd_per_kg, ...
    'lookahead_steps', lookahead_steps, ...
    'raw_deficit_quantile_kg', raw_deficit_quantile_kg, ...
    'deficit_quantile_kg', deficit_quantile_kg, ...
    'surplus_charge_cap_kg', surplus_charge_cap_kg, ...
    'renewable_capped', reserve_target_kg < storage_limits.min_mass ...
        + min(storage_limits.work_mass, deficit_quantile_kg) ...
        - 1e-9, ...
    'target_min_kg', target_kg, ...
    'target_work_soc', ...
        (target_kg - storage_limits.min_mass) ...
        / storage_limits.work_mass);
end

