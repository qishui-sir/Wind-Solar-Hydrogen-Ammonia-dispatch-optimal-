function validate_configuration(config, renewable_data, subprotocol, ...
        scheme, forecast_mode)
if ~protocol_v5('verify_v5_1', subprotocol)
    error('rolling_dispatch:bad_protocol', ...
        'Protocol v5.1 verification failed.');
end
supported_schemes = [ ...
    "economic_only", ...
    "contract_plan_and_hb_smoothing"];
if ~isscalar(scheme) || ~ismember(scheme, supported_schemes)
    error('rolling_dispatch:unsupported_scheme', ...
        'The current closed loop supports economic_only and contract planning.');
end
if ~isscalar(forecast_mode) || ...
        ~ismember(forecast_mode, ...
        ["simulated_persistence", "observed_oracle", "table"])
    error('rolling_dispatch:bad_forecast_mode', ...
        ['forecast_mode must be simulated_persistence, ', ...
         'observed_oracle, or table.']);
end
reserve_quantile = option_value(config, 'carbon_reserve_quantile', ...
    default_carbon_reserve_quantile());
if ~(isnumeric(reserve_quantile) && isscalar(reserve_quantile) && ...
        isfinite(reserve_quantile) && reserve_quantile >= 0 && ...
        reserve_quantile <= 1)
    error('rolling_dispatch:bad_carbon_reserve_quantile', ...
        'carbon_reserve_quantile must be a finite scalar in [0, 1].');
end
dt = renewable_data_time_step(renewable_data);
samples_per_day = 24 / dt;
if abs(samples_per_day - round(samples_per_day)) > 1e-9 || ...
        mod(renewable_data.time_count, round(samples_per_day)) ~= 0
    error('rolling_dispatch:incomplete_days', ...
        'Input must contain complete operating days.');
end
if subprotocol.RollingDispatch.PlanningHours ~= 72 || ...
        subprotocol.RollingDispatch.CommitHours ~= 24
    error('rolling_dispatch:protocol_horizon_drift', ...
        'The implementation requires the frozen 72/24-hour protocol.');
end
end

